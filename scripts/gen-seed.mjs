// Generates supabase/seed-quotes.sql from src/data/quotes.ts.
// Usage: npm run seed:quotes   (Node ≥ 23 runs TypeScript natively)
import { SEED_QUOTES } from "../src/data/quotes.ts";

const esc = (s) => s.replace(/'/g, "''");

const values = SEED_QUOTES.map(
  ([ru, en, author, category]) =>
    `  ('${esc(ru)}', '${esc(en)}', '${esc(author)}', '${category}')`,
);

process.stdout.write(
  `-- Generated by scripts/gen-seed.mjs — do not edit by hand.\n` +
    `-- Apply after 0001_init.sql in the Supabase SQL editor.\n` +
    `insert into public.quotes (text_ru, text_en, author, category) values\n` +
    values.join(",\n") +
    `\n;\n`,
);
